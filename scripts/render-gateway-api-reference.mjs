// Project the canonical Gateway contract of one published release into Mintlify.
// Gateway has no product CLI surface, so this projection emits API pages only.
import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { openApiPaths, withoutAliasPaths } from './render-api-surface-reference.mjs'
import { LOCALES, sync as syncNavigation } from './i18n/sync-navigation.mjs'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const source = 'identity/reference/api/openapi.yaml'
const directory = 'identity/reference/api'
const generator = 'render-gateway-api-reference'

function requireValue(condition, message) {
  if (!condition) throw new Error(message)
}

export function renderGatewayReference({ openapi, release, sourceSha }) {
  requireValue(/^v\d+\.\d+\.\d+$/.test(release), 'Use an actual published Gateway product release tag')
  requireValue(/^[a-f0-9]{40}$/.test(sourceSha), 'Use the full immutable release source SHA')
  const normalized = openapi.replace(/^\uFEFF/, '').replaceAll('\r\n', '\n')
  requireValue(/^openapi:\s*['"]?3\.1\./m.test(normalized), 'Gateway contract must be OpenAPI 3.1')
  requireValue(/^  title:\s*['"]?kombify Gateway API['"]?\s*$/m.test(normalized), 'Expected the canonical Gateway API contract')
  requireValue(!/^\s*(?:-\s+)?['"]?x-kombify-[a-z-]+['"]?\s*:/m.test(normalized), 'Public contract must not contain internal x-kombify annotations')
  const paths = openApiPaths(normalized)
  requireValue(paths.length > 0 && paths.includes('/gateway/health'), 'Gateway contract needs its public edge paths')
  requireValue(paths.every(route => !/(^|\/)internal(\/|$)/i.test(route)), 'Public contract contains an internal route')
  const contentHash = `sha256:${createHash('sha256').update(normalized).digest('hex')}`
  const header = [
    `# Generated by ${generator}; do not edit.`,
    `# Gateway release: ${release}`,
    `# Source: ${sourceSha}:docs/openapi.yaml`,
    `# Content hash: ${contentHash}`,
    '# This reference describes that published release, not an unqualified newer runtime.',
    '',
  ].join('\n')
  return { content: header + withoutAliasPaths(normalized).replace(/\s*$/, '\n'), contentHash, paths: paths.length }
}

function requireAdvance(held, { release, sourceSha, contentHash }) {
  const previous = /^# Gateway release: (v\d+\.\d+\.\d+)$/m.exec(held)?.[1]
  const previousSource = /^# Source: ([a-f0-9]{40}):docs\/openapi\.yaml$/m.exec(held)?.[1]
  const previousHash = /^# Content hash: (sha256:[a-f0-9]{64})$/m.exec(held)?.[1]
  requireValue(previous && previousSource && previousHash, 'Existing Gateway reference has no qualified release identity')
  const oldVersion = previous.slice(1).split('.').map(BigInt)
  const nextVersion = release.slice(1).split('.').map(BigInt)
  const differing = nextVersion.findIndex((number, index) => number !== oldVersion[index])
  requireValue(differing < 0 || nextVersion[differing] > oldVersion[differing], `Refusing Gateway reference downgrade from ${previous} to ${release}`)
  requireValue(release !== previous || (sourceSha === previousSource && contentHash === previousHash), 'Published Gateway release identity changed; inspect its source before any write')
}

export function syncGatewayReference({ repoRoot = root, openapi, release, sourceSha, mode, previous }) {
  requireValue(mode === 'write' || mode === 'check', 'Choose write or check')
  const rendered = renderGatewayReference({ openapi, release, sourceSha })
  const specPath = path.join(repoRoot, source)
  const identity = { release, sourceSha, contentHash: rendered.contentHash }
  if (existsSync(specPath)) requireAdvance(readFileSync(specPath, 'utf8'), identity)
  if (previous !== undefined) requireAdvance(previous, identity)
  const docsPath = path.join(repoRoot, 'docs.json')
  const original = readFileSync(docsPath, 'utf8')
  const docs = JSON.parse(original)
  const english = docs.navigation?.languages?.find(branch => branch.language === 'en')
  const tab = english?.tabs?.find(candidate => candidate.tab === 'Identity & Access')
  requireValue(Array.isArray(tab?.groups), 'Missing public Identity & Access navigation')
  const group = { group: 'Gateway API', icon: 'code', openapi: { source, directory } }
  const existing = tab.groups.findIndex(candidate => candidate.openapi?.source === source)
  if (existing < 0) tab.groups.push(group)
  else tab.groups[existing] = group
  const nextDocs = `${JSON.stringify(syncNavigation(docs, Object.keys(LOCALES)), null, 2)}\n`
  const drift = []
  if (!existsSync(specPath) || readFileSync(specPath, 'utf8') !== rendered.content) drift.push(source)
  if (original !== nextDocs) drift.push('docs.json')
  if (mode === 'write') {
    mkdirSync(path.dirname(specPath), { recursive: true })
    writeFileSync(specPath, rendered.content)
    writeFileSync(docsPath, nextDocs)
  }
  return { release, sourceSha, contentHash: rendered.contentHash, paths: rendered.paths, locales: 1 + Object.keys(LOCALES).length, drift: mode === 'check' ? drift : [] }
}

function main() {
  const args = process.argv.slice(2)
  const options = {}
  for (let index = 0; index < args.length; index++) {
    const name = args[index]
    if (name === '--write' || name === '--check') {
      requireValue(!options.mode, 'Choose exactly one mode')
      options.mode = name.slice(2)
    } else {
      requireValue(['--openapi', '--release', '--source-sha', '--previous'].includes(name), `Unknown option ${name}`)
      requireValue(!Object.hasOwn(options, name) && typeof args[index + 1] === 'string', `Missing or duplicate ${name}`)
      options[name] = args[++index]
    }
  }
  requireValue(options.mode && options['--openapi'] && options['--release'] && options['--source-sha'], 'Usage: render-gateway-api-reference.mjs --openapi <published contract> --release <tag> --source-sha <sha> (--write | --check)')
  const result = syncGatewayReference({ openapi: readFileSync(path.resolve(options['--openapi']), 'utf8'), release: options['--release'], sourceSha: options['--source-sha'], mode: options.mode,
    ...(options['--previous'] ? { previous: readFileSync(path.resolve(options['--previous']), 'utf8') } : {}) })
  console.log(JSON.stringify(result))
  if (result.drift.length) process.exitCode = 1
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) main()
