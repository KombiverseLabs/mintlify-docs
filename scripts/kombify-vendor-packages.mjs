#!/usr/bin/env node
// Vendors the private @kombiverselabs packages a repository consumes into
// vendor/npm/ and points pnpm at them, so `pnpm install` needs no registry
// token in any environment: Claude, Codex, Cursor, workstations and CI
// (SECRETS-ACCESS-STANDARD §6d, owner decision 2026-10-10). The packages stay
// private; the tarballs live only in the private consumer repository.
//
//   node scripts/kombify-vendor-packages.mjs            # vendor what package.json pins
//   node scripts/kombify-vendor-packages.mjs --latest   # move every pin to the newest release first
//   node scripts/kombify-vendor-packages.mjs --release @kombiverselabs/embed@1.2.3
//       # move that package to a just-published release; pins its chain requires follow it
//   node scripts/kombify-vendor-packages.mjs --check    # offline: vendored set matches package.json
//
// package.json stays the source of truth for versions (direct names and npm:
// aliases). Syncing downloads each pinned version plus the @kombiverselabs
// packages those depend on, verifies the registry integrity, removes stale
// tarballs and rewrites the generated overrides block in pnpm-workspace.yaml.
// Run `pnpm install` afterwards to refresh the lockfile. Downloads need a
// read:packages token in NODE_AUTH_TOKEN: CI passes its token, a session runs
// `node scripts/kombify-bootstrap.mjs packages -- node scripts/kombify-vendor-packages.mjs`.
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

export const SCOPE = '@kombiverselabs';
export const REGISTRY = 'https://npm.pkg.github.com';
export const VENDOR_DIR = 'vendor/npm';
const START = '  # kombify-vendor:start (generated by scripts/kombify-vendor-packages.mjs; do not edit)';
const END = '  # kombify-vendor:end';
const SECTIONS = ['dependencies', 'devDependencies', 'optionalDependencies'];

// --- semver subset: exact, ^, ~, >=, x/* ------------------------------------
export function parseVersion(value) {
  const match = /^v?(\d+)\.(\d+)\.(\d+)(?:-([0-9A-Za-z.-]+))?(?:\+.*)?$/.exec(String(value).trim());
  return match ? { major: +match[1], minor: +match[2], patch: +match[3], pre: match[4] ?? '' } : null;
}
export function compareVersions(a, b) {
  const x = parseVersion(a); const y = parseVersion(b);
  for (const key of ['major', 'minor', 'patch']) if (x[key] !== y[key]) return x[key] - y[key];
  if (x.pre === y.pre) return 0;
  if (!x.pre) return 1;
  if (!y.pre) return -1;
  return x.pre < y.pre ? -1 : 1;
}
export function satisfies(version, range) {
  const v = parseVersion(version);
  if (!v) return false;
  const spec = String(range).trim();
  if (spec === '' || spec === '*' || spec === 'latest' || spec === 'x') return !v.pre;
  return spec.split('||').some((alternative) => alternative.trim().split(/\s+/).every((part) => {
    const op = /^(\^|~|>=|<=|>|<|=)?(.*)$/.exec(part);
    const base = op[2].replace(/\.[x*]/g, '.0');
    const wildcard = /\.[x*]/.test(op[2]) || /^\d+(\.\d+)?$/.test(op[2]);
    const parts = op[2].split('.');
    const b = parseVersion(/^\d+$/.test(base) ? `${base}.0.0` : /^\d+\.\d+$/.test(base) ? `${base}.0` : base);
    if (!b) return false;
    if (v.pre && (v.major !== b.major || v.minor !== b.minor || v.patch !== b.patch)) return false;
    const cmp = compareVersions(version, `${b.major}.${b.minor}.${b.patch}${b.pre ? `-${b.pre}` : ''}`);
    switch (op[1]) {
      case '^': return cmp >= 0 && (b.major > 0 ? v.major === b.major : b.minor > 0 ? v.major === 0 && v.minor === b.minor : v.major === 0 && v.minor === 0 && v.patch === b.patch);
      case '~': return cmp >= 0 && v.major === b.major && v.minor === b.minor;
      case '>=': return cmp >= 0;
      case '>': return cmp > 0;
      case '<=': return cmp <= 0;
      case '<': return cmp < 0;
      default:
        if (wildcard) return v.major === b.major && (parts.length < 2 || /[x*]/.test(parts[1]) || v.minor === b.minor);
        return cmp === 0;
    }
  }));
}
export function maxSatisfying(versions, range) {
  return versions.filter((version) => satisfies(version, range)).sort(compareVersions).at(-1) ?? null;
}

// --- repository scan ---------------------------------------------------------
export function manifestPaths(root) {
  let listed;
  try {
    listed = execFileSync('git', ['ls-files', '-co', '--exclude-standard', '--', 'package.json', '**/package.json'], { cwd: root, encoding: 'utf8' })
      .split('\n').filter(Boolean);
  } catch { listed = existsSync(join(root, 'package.json')) ? ['package.json'] : []; }
  return listed.filter((path) => !path.split('/').some((part) => part === 'node_modules' || part === 'vendor'));
}

/** Every consumed @kombiverselabs package: { alias, name, range, file, section }. */
export function consumedPackages(root, read = (path) => readFileSync(path, 'utf8')) {
  const found = [];
  const other = new Map();
  for (const file of manifestPaths(root)) {
    const manifest = JSON.parse(read(join(root, file)));
    for (const section of SECTIONS) {
      for (const [alias, specifier] of Object.entries(manifest[section] ?? {})) {
        const aliased = /^npm:(@kombiverselabs\/[^@]+)@(.+)$/.exec(specifier);
        if (aliased) found.push({ alias, name: aliased[1], range: aliased[2], file, section });
        else if (alias.startsWith(`${SCOPE}/`) && !/^(workspace|file|link|git|github|https?):/.test(specifier)) found.push({ alias, name: alias, range: specifier, file, section });
        else other.set(alias, `${file} (${specifier})`);
      }
    }
  }
  // A direct alias override applies repository-wide, so its name must not
  // also name another package here (a workspace package, for example).
  for (const { alias, name, file } of found) {
    if (alias !== name && other.has(alias)) throw new Error(`${file}: alias ${alias} also names ${other.get(alias)}; rename the alias`);
  }
  // Names this repository itself provides (workspace:/link:/file: pins).
  found.localNames = new Set(other.keys());
  return found;
}

export const tarballName = (name, version) => `${name.slice(1).replace('/', '-')}-${version}.tgz`;

/** The generated overrides lines, keyed by real names and npm: alias names. */
export function overrideLines(resolved, consumed, scoped = []) {
  const lines = new Map();
  const scopedNames = new Set(scoped.map(({ name }) => name));
  for (const [name, version] of [...resolved].sort(([a], [b]) => a.localeCompare(b))) if (!scopedNames.has(name)) lines.set(name, `file:${VENDOR_DIR}/${tarballName(name, version)}`);
  // A vendored package that this repository also provides locally is scoped
  // to the vendored parents, so workspace: and link: consumers keep the source.
  for (const { alias, name } of scoped) lines.set(alias, `file:${VENDOR_DIR}/${tarballName(name, resolved.get(name))}`);
  for (const { alias, name } of consumed) if (alias !== name && resolved.has(name)) lines.set(alias, lines.get(name));
  return [...lines].sort(([a], [b]) => a.localeCompare(b)).map(([key, target]) => `  "${key}": "${target}"`);
}

export function writeOverrides(text, lines) {
  const block = [START, ...lines, END].join('\n');
  const source = text ?? '';
  const start = source.indexOf(START);
  if (start >= 0) {
    const end = source.indexOf(END, start);
    if (end < 0) throw new Error('pnpm-workspace.yaml has a kombify-vendor:start marker without its end marker');
    return `${source.slice(0, start)}${block}${source.slice(end + END.length)}`;
  }
  if (/^overrides:[ \t]*$/m.test(source)) return source.replace(/^overrides:[ \t]*$/m, `overrides:\n${block}`);
  return `${source}${source && !source.endsWith('\n') ? '\n' : ''}overrides:\n${block}\n`;
}

// --- registry ----------------------------------------------------------------
async function registryJson(name, token, fetchImpl) {
  const response = await fetchImpl(`${REGISTRY}/${name.replace('/', '%2f')}`, { headers: { Authorization: `Bearer ${token}`, Accept: 'application/json' } });
  if (!response.ok) throw new Error(`${name}: registry metadata refused (HTTP ${response.status})`);
  return response.json();
}

/**
 * One vendored version per package (the overrides force it everywhere), so the
 * chosen version is the newest one that satisfies every constraint: the
 * package.json pins (ignored with --latest, which moves them; with --release a
 * pin that conflicts with the released chain follows it) and the ranges
 * the other vendored packages declare. Those yield to a repository pin of the
 * same package; any other conflict fails closed.
 */
export async function resolvePackages(consumed, { token, latest = false, release = new Map(), fetchImpl = fetch }) {
  const documents = new Map();
  const document = async (name) => {
    if (!documents.has(name)) documents.set(name, await registryJson(name, token, fetchImpl));
    return documents.get(name);
  };
  const direct = new Map();
  for (const entry of consumed) direct.set(entry.name, [...(direct.get(entry.name) ?? []), entry]);
  let resolved = new Map();
  let aliases = [];
  const directAliases = new Set(consumed.filter(({ alias, name }) => alias !== name).map(({ alias }) => alias));
  let scoped = [];
  for (let round = 0; round < 20; round += 1) {
    const constraints = new Map();
    const add = (name, range, from, soft = false) => constraints.set(name, [...(constraints.get(name) ?? []), { range, from, soft }]);
    for (const [name, entries] of direct) {
      if (latest) add(name, '*', 'latest');
      else if (release.has(name)) add(name, release.get(name), 'release');
      else for (const entry of entries) constraints.set(name, [...(constraints.get(name) ?? []), { range: entry.range, from: entry.file, soft: release.size > 0 }]);
    }
    aliases = [];
    scoped = [];
    for (const [name, version] of resolved) {
      const manifest = (await document(name)).versions[version];
      for (const deps of [manifest.dependencies, manifest.peerDependencies, manifest.optionalDependencies]) {
        for (const [key, specifier] of Object.entries(deps ?? {})) {
          const aliased = /^npm:(@kombiverselabs\/[^@]+)@(.+)$/.exec(specifier);
          const dependency = aliased ? aliased[1] : key;
          if (!dependency.startsWith(`${SCOPE}/`)) continue;
          // The repository's own alias of that name is the global override and wins.
          if (aliased && directAliases.has(key)) continue;
          // Scoped to the parent: the alias name may also be a workspace package.
          if (aliased) aliases.push({ alias: `${name}>${key}`, name: dependency });
          else if (!direct.has(dependency) && consumed.localNames?.has(dependency)) scoped.push({ alias: `${name}>${dependency}`, name: dependency });
          // A repository pin wins over a vendored package's own pin: the
          // overrides force the pinned version on that package as well.
          add(dependency, aliased ? aliased[2] : specifier, `${name}@${version}`, !latest && !release.size && direct.has(dependency));
        }
      }
    }
    const next = new Map();
    for (const [name, ranges] of constraints) {
      const versions = Object.keys((await document(name)).versions ?? {});
      const pick = (list) => versions.filter((version) => list.every(({ range }) => satisfies(version, range))).sort(compareVersions).at(-1);
      const chosen = pick(ranges) ?? pick(ranges.filter(({ soft }) => !soft));
      if (!chosen) throw new Error(`${name}: no published version satisfies ${ranges.map(({ range, from }) => `${range} (${from})`).join(', ')}`);
      next.set(name, chosen);
    }
    const stable = next.size === resolved.size && [...next].every(([name, version]) => resolved.get(name) === version);
    resolved = next;
    if (stable) return { resolved, aliases, scoped, manifests: (name, version) => documents.get(name).versions[version] };
  }
  throw new Error('package versions did not settle; check for circular version constraints');
}

function integrityOk(bytes, dist) {
  if (typeof dist?.integrity === 'string' && dist.integrity.startsWith('sha512-')) {
    return createHash('sha512').update(bytes).digest('base64') === dist.integrity.slice('sha512-'.length);
  }
  if (typeof dist?.shasum === 'string') return createHash('sha1').update(bytes).digest('hex') === dist.shasum;
  return false;
}

// --- commands ----------------------------------------------------------------
function updatePins(root, consumed, resolved) {
  const byFile = new Map();
  for (const entry of consumed) byFile.set(entry.file, [...(byFile.get(entry.file) ?? []), entry]);
  for (const [file, entries] of byFile) {
    const path = join(root, file);
    const text = readFileSync(path, 'utf8');
    const manifest = JSON.parse(text);
    for (const { alias, name, section } of entries) {
      const version = resolved.get(name);
      manifest[section][alias] = alias === name ? version : `npm:${name}@${version}`;
    }
    const indent = /^(\s+)"/m.exec(text)?.[1] ?? '  ';
    writeFileSync(path, `${JSON.stringify(manifest, null, indent)}\n`);
  }
}

export async function sync({ root = process.cwd(), latest = false, release = new Map(), token = process.env.NODE_AUTH_TOKEN, fetchImpl = fetch } = {}) {
  const consumed = consumedPackages(root);
  const workspaceFile = join(root, 'pnpm-workspace.yaml');
  if (!consumed.length) return { resolved: new Map(), changed: false };
  if (!token) throw new Error('NODE_AUTH_TOKEN is not set. Run: node scripts/kombify-bootstrap.mjs packages -- node scripts/kombify-vendor-packages.mjs');
  for (const name of release.keys()) if (!consumed.some((entry) => entry.name === name)) throw new Error(`${name} is not a dependency of this repository`);
  const { resolved, aliases, scoped, manifests } = await resolvePackages(consumed, { token, latest, release, fetchImpl });
  if (latest || release.size) updatePins(root, consumed.filter((entry) => latest || release.has(entry.name) || !satisfies(resolved.get(entry.name), entry.range)), resolved);
  const dir = join(root, VENDOR_DIR);
  mkdirSync(dir, { recursive: true });
  const wanted = new Set();
  for (const [name, version] of resolved) {
    const file = tarballName(name, version);
    wanted.add(file);
    const target = join(dir, file);
    const dist = manifests(name, version).dist;
    if (existsSync(target) && integrityOk(readFileSync(target), dist)) continue;
    const response = await fetchImpl(dist.tarball, { headers: { Authorization: `Bearer ${token}` } });
    if (!response.ok) throw new Error(`${name}@${version}: tarball download refused (HTTP ${response.status})`);
    const bytes = Buffer.from(await response.arrayBuffer());
    if (!integrityOk(bytes, dist)) throw new Error(`${name}@${version}: tarball does not match the registry integrity`);
    writeFileSync(target, bytes);
  }
  for (const file of readdirSync(dir)) if (file.endsWith('.tgz') && !wanted.has(file)) rmSync(join(dir, file));
  const before = existsSync(workspaceFile) ? readFileSync(workspaceFile, 'utf8') : null;
  const after = writeOverrides(before, overrideLines(resolved, [...consumed, ...aliases], scoped));
  if (after !== before) writeFileSync(workspaceFile, after);
  return { resolved, changed: after !== before };
}

/** Offline consistency check for CI: no network, no token. */
export function check(root = process.cwd()) {
  const consumed = consumedPackages(root);
  const problems = [];
  if (!consumed.length) return problems;
  const dir = join(root, VENDOR_DIR);
  const files = existsSync(dir) ? readdirSync(dir).filter((file) => file.endsWith('.tgz')) : [];
  const workspaceFile = join(root, 'pnpm-workspace.yaml');
  const text = existsSync(workspaceFile) ? readFileSync(workspaceFile, 'utf8') : '';
  const start = text.indexOf(START);
  const end = text.indexOf(END);
  if (start < 0 || end < 0) return [`${workspaceFile}: generated kombify-vendor overrides block is missing`];
  const overrides = new Map([...text.slice(start, end).matchAll(/^\s+"([^"]+)": "file:([^"]+)"$/gm)].map((match) => [match[1], match[2]]));
  const targets = new Set([...overrides.values()].map((target) => target.slice(VENDOR_DIR.length + 1)));
  for (const { alias, name, range, file } of consumed) {
    const target = overrides.get(alias);
    if (!target) { problems.push(`${file}: ${alias} has no vendored override`); continue; }
    if (overrides.get(name) !== target) problems.push(`${file}: ${alias} and ${name} point at different tarballs`);
    const version = /-(\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?)\.tgz$/.exec(target)?.[1];
    if (!version || !satisfies(version, range)) problems.push(`${file}: ${alias}@${range} is vendored as ${version ?? target}`);
  }
  for (const target of targets) if (!files.includes(target)) problems.push(`${VENDOR_DIR}/${target} is missing`);
  for (const file of files) if (!targets.has(file)) problems.push(`${VENDOR_DIR}/${file} is not referenced by an override`);
  return problems;
}

async function main(argv) {
  const root = resolve(process.cwd());
  if (argv.includes('--check')) {
    const problems = check(root);
    for (const problem of problems) console.error(`KOMBIFY_VENDOR_DRIFT ${problem}`);
    if (problems.length) {
      console.error('Fix: node scripts/kombify-bootstrap.mjs packages -- node scripts/kombify-vendor-packages.mjs && pnpm install');
      process.exitCode = 1;
    } else console.log('KOMBIFY_VENDOR_OK');
    return;
  }
  const release = new Map();
  for (let index = argv.indexOf('--release'); index >= 0; index = argv.indexOf('--release', index + 1)) {
    const match = /^(@kombiverselabs\/[^@]+)@(\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?)$/.exec(argv[index + 1] ?? '');
    if (!match) throw new Error('--release needs @kombiverselabs/<name>@<exact version>');
    release.set(match[1], match[2]);
  }
  const { resolved, changed } = await sync({ root, latest: argv.includes('--latest'), release });
  console.log(`KOMBIFY_VENDOR_SYNCED packages=${resolved.size} overrides_changed=${changed}`);
  if (resolved.size) console.log('Next: pnpm install (refreshes pnpm-lock.yaml from the vendored tarballs)');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  main(process.argv.slice(2)).catch((error) => { console.error(`KOMBIFY_VENDOR_ERROR ${error.message}`); process.exitCode = 1; });
}
